/** 为自定义问题生成一个与预设包同构的问题包。同一问题 → 同一宇宙。 */
export function generatePack(q) {
  const a = analyzeQuestion(q);
  const rand = makeRand(hashStr(a.clean || a.raw));
  const cards = []
    .concat(stories(a, rand))
    .concat(facts(a, rand))
    .concat(views(a, rand))
    .concat(persons(a, rand))
    .concat(blinds(a, rand));
  return {
    id: 'custom',
    q: a.raw,
    sub: SUBS[a.shape] || SUBS.open,
    cards: cards
  };
}
