// 归一宇宙 — 自定义问题的个性化生成。
// 把用户的问题解析成「问题形状」，再为五座认知岛各生成一组围绕该问题的卡。
// 同一问题生成同一宇宙（确定性），存档恢复后内容完全一致。

function hashStr(s) {
  let h = 2166136261 >>> 0;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function makeRand(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function pickN(rand, arr, n) {
  const pool = arr.slice();
  const out = [];
  while (out.length < n && pool.length) out.push(pool.splice(Math.floor(rand() * pool.length), 1)[0]);
  return out;
}

function pick1(rand, arr) { return arr[Math.floor(rand() * arr.length) % arr.length]; }

/** 解析问题：形状 + 主题短语 +（选择类的）两个选项。 */
export function analyzeQuestion(q) {
  const raw = String(q || '').trim();
  const clean = raw.replace(/[？?！!]+$/, '');
  const clauses = clean.split(/[，,。；;、]/).map(function (s) { return s.trim(); }).filter(Boolean);
  const tail = clauses[clauses.length - 1] || clean;
  const context = clauses.length > 1 ? clauses.slice(0, -1).join('，') : '';
  let topic = tail
    .replace(/^(那|那么|所以|请问|你说|到底|究竟|我就想问|就是想问)/, '')
    .replace(/(吗|呢|么|吧|啊)$/, '')
    .trim() || tail.trim();
  const isChoice = /还是/.test(tail);
  let optA = null; let optB = null;
  if (isChoice) {
    const i = tail.indexOf('还是');
    optA = (tail.slice(0, i).replace(/^(到底|究竟|该|要|会|先|是)/, '').trim() || '这条路');
    optB = (tail.slice(i + 2).replace(/(吗|呢|么|吧|啊)$/, '').trim() || '那条路');
  }
  const yesno = !isChoice && /(会不会|能不能|要不要|该不该|可不可以|是不是|有没有|值不值|来不来得及|[吗么])$/.test(tail);
  const whenish = !isChoice && !yesno && /(来得及|什么时候|多久|晚不晚|赶得上|几年|几岁)/.test(tail);
  const howish = !isChoice && /(怎么|怎样|如何|怎么办)/.test(tail);
  const whyish = !isChoice && /(为什么|为何)/.test(tail);
  const shape = isChoice ? 'choice' : yesno ? 'yesno' : whenish ? 'when' : howish ? 'how' : whyish ? 'why' : 'open';
  return { raw: raw, clean: clean, tail: tail, topic: topic, context: context, optA: optA, optB: optB, shape: shape };
}

